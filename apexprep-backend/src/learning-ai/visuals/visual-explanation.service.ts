import { AuditService } from '../../audit/audit.service';
import type { AuthContext } from '../../common/auth/auth-context';
import { AppException } from '../../common/errors/app-exception';
import { isUniqueViolation } from '../../database/pg-error';
import type { VisualExplanationRow, VisualType } from '../../database/schema';
import { EngineConfigService } from '../../engine-config/engine-config.service';
import { parseExplanationParams, type ExplanationParams } from '../../explanations/explanation-params';
import { TheoryRetrievalService } from '../../explanations/theory-retrieval.service';
import { PracticeRepository } from '../../practice/practice.repository';
import { QuestionsService } from '../../questions/questions.service';
import { buildAssetKey, OBJECT_STORAGE, sha256Hex, type ObjectStorage } from '../../storage/object-storage';
import { audienceFor } from '../audience';
import type { VisualExplanationDto } from '../dto/learning-ai.dto';
import { LearningAiRepository } from '../learning-ai.repository';
import { sourceHash } from '../source';
import { toLeakAnswer } from '../tutor/tutor.service';
import { parseVisualReply, validateVisual, type VisualReply, type VisualValidation } from './scene';
import { buildVisualPrompt, VISUAL_PROMPT_VERSION } from './visual.prompt';

const REJECTION_COOLDOWN_MS = 30 * 60 * 1000;
const OUTPUT_TOKENS = 8192;
/** One corrective retry after a rejected draft; a second failure is recorded and the question stays text-only. */
const MAX_ATTEMPTS = 2;

/**
 * "Explain visually": a visual the student asks for, chosen by an analysis of the question rather than a
 * picture generated by default.
 *
 * The analysis decides the concept, whether a visual helps at all, and the best format — diagram, graph,
 * step-by-step, animation, illustration, an image only when nothing drawn will do, or none. Drawn formats
 * are a validated scene the frontend renders; nothing executable crosses the wire. An image, when an image
 * model is configured, goes through object storage and a `content_assets` row like any uploaded file.
 * Video is deliberately not generated: no source of vetted educational videos exists in the platform,
 * and a model-suggested link is not one.
 *
 * Cached per question version, keyed on the notes the analysis read and the prompt version; a "no visual
 * would help" outcome is cached too, so the question is not re-analysed on every click. When anything
 * fails the question is untouched and practice carries on — the frontend shows the text explanation.
 */
@Injectable()
export class VisualExplanationService {
  private readonly logger = new Logger(VisualExplanationService.name);

  constructor(
    private readonly repo: LearningAiRepository,
    private readonly ai: AiService,
    private readonly engineConfig: EngineConfigService,
    private readonly retrieval: TheoryRetrievalService,
    private readonly practice: PracticeRepository,
    private readonly questions: QuestionsService,
    private readonly audit: AuditService,
    @Inject(OBJECT_STORAGE) private readonly storage: ObjectStorage,
  ) {}

  async forQuestion(auth: AuthContext, questionId: string): Promise<VisualExplanationDto> {
    const question = await this.questions.studentView(auth.tenantId, questionId);
    const ctx = await this.repo.subtopicContext(auth.tenantId, question.subtopicId);
    if (!ctx) throw AppException.notFound('Question not found');
    const key = await this.practice.questionForGrading(auth.tenantId, question.id);
    if (!key) throw AppException.notFound('Question not found');

    const params = await this.explanationParams(auth.tenantId);
    const retrieval = await this.retrieval.retrieve(auth.tenantId, { subtopicId: ctx.subtopicId, topicId: ctx.topicId, chapterId: ctx.chapterId }, question.stem, params);
    const chunks = retrieval.selected.map((c) => c.chunk);
    const hash = sourceHash(await this.repo.blockHashes(auth.tenantId, [...new Set(chunks.flatMap((c) => c.blockIds))]));

    const active = await this.repo.activeVisual(auth.tenantId, question.id, question.version);
    if (active && active.sourceHash === hash && active.promptVersion === VISUAL_PROMPT_VERSION) return this.toDto(active, true);
    if (await this.repo.recentRejectedVisual(auth.tenantId, question.id, question.version, hash, VISUAL_PROMPT_VERSION, new Date(Date.now() - REJECTION_COOLDOWN_MS))) {
      throw this.rejected();
    }
    if (!this.ai.configured) {
      throw AppException.unavailable('Visual explanations need an AI provider, and none is configured on this server', 'AI_NOT_CONFIGURED');
    }

    const leakAnswer = toLeakAnswer(question, key);
    const imagesAvailable = this.ai.imageProvider() !== null;
    let problems: string[] = [];
    let reply: { provider: string; model: string; value: VisualReply } | null = null;
    let validation: VisualValidation | null = null;
    for (let attempt = 0; attempt < MAX_ATTEMPTS; attempt += 1) {
      reply = await this.ai.generateJson(
        {
          task: 'visual',
          temperature: 0.3,
          maxOutputTokens: OUTPUT_TOKENS,
          prompt: buildVisualPrompt({
            audience: audienceFor(ctx.track),
            subtopicPath: `${ctx.subjectName} › ${ctx.chapterName} › ${ctx.topicName} › ${ctx.subtopicName}`,
            question: { type: question.type, stem: question.stem, options: question.options },
            chunks,
            imagesAvailable,
            previousProblems: problems,
          }),
        },
        parseVisualReply,
      );
      validation = validateVisual(reply.value, leakAnswer);
      if (validation.ok) break;
      problems = validation.failures;
    }

    if (!reply || !validation?.ok) {
      const row = await this.repo.insertVisual({
        tenantId: auth.tenantId,
        questionId: question.id,
        questionVersion: question.version,
        promptVersion: VISUAL_PROMPT_VERSION,
        sourceHash: hash,
        status: 'rejected',
        visualType: reply?.value.format ?? 'none',
        decision: reply ? decisionOf(reply.value) : {},
        spec: null,
        provider: reply?.provider ?? null,
        model: reply?.model ?? null,
        validation: { ok: false, failures: validation?.failures ?? [], leaks: validation?.leaks ?? [] },
        requestedBy: auth.userId,
      });
      await this.audit.record({
        tenantId: auth.tenantId,
        action: 'visual_explanation.rejected',
        entityType: 'visual_explanation',
        entityId: row.id,
        after: { questionId: question.id, failures: validation?.failures.slice(0, 10) ?? [], leaked: (validation?.leaks.length ?? 0) > 0 },
      });
      throw this.rejected();
    }

    const outcome = await this.materialise(auth, reply.value, validation);
    let row: VisualExplanationRow;
    try {
      if (active) await this.repo.supersedeVisual(auth.tenantId, active.id);
      row = await this.repo.insertVisual({
        tenantId: auth.tenantId,
        questionId: question.id,
        questionVersion: question.version,
        promptVersion: VISUAL_PROMPT_VERSION,
        sourceHash: hash,
        status: 'active',
        visualType: outcome.type,
        decision: { ...decisionOf(reply.value), ...(outcome.note ? { note: outcome.note } : {}) },
        spec: outcome.spec,
        assetId: outcome.assetId,
        provider: reply.provider,
        model: reply.model,
        validation: { ok: true, requestedFormat: reply.value.format },
        requestedBy: auth.userId,
      });
    } catch (error) {
      if (!isUniqueViolation(error)) throw error;
      const winner = await this.repo.activeVisual(auth.tenantId, question.id, question.version);
      if (!winner) throw error;
      return this.toDto(winner, true);
    }

    await this.audit.record({
      tenantId: auth.tenantId,
      action: 'visual_explanation.generated',
      entityType: 'visual_explanation',
      entityId: row.id,
      after: { questionId: question.id, visualType: row.visualType, requestedFormat: reply.value.format, provider: reply.provider, model: reply.model },
    });
    return this.toDto(row, false);
  }

  /** The stored image of an image visual, for the student's browser. */
  async image(auth: AuthContext, id: string): Promise<{ bytes: Buffer; contentType: string }> {
    const visual = await this.repo.findVisual(auth.tenantId, id);
    if (!visual?.assetId) throw AppException.notFound('Image not found');
    // Only for a question the student can see.
    await this.questions.studentView(auth.tenantId, visual.questionId);
    const asset = await this.repo.findAsset(auth.tenantId, visual.assetId);
    if (!asset) throw AppException.notFound('Image not found');
    return { bytes: await this.storage.get(asset.storageKey), contentType: asset.mimeType };
  }

  // ---------------------------------------------------------------- internals

  /**
   * What gets stored for a validated reply. An image is generated only when an image model is configured
   * and the analysis chose one; if generation fails the drawn fallback scene is used, so a flaky image
   * provider costs quality, never the feature.
   */
  private async materialise(
    auth: AuthContext,
    reply: VisualReply,
    validation: VisualValidation,
  ): Promise<{ type: VisualType; spec: Record<string, unknown> | null; assetId: string | null; note: string | null }> {
    const scene = validation.scene as unknown as Record<string, unknown> | null;
    if (reply.format === 'none') return { type: 'none', spec: null, assetId: null, note: null };
    if (reply.format !== 'image') return { type: reply.format, spec: scene, assetId: null, note: null };

    if (this.ai.imageProvider() && reply.imagePrompt) {
      try {
        const image = await this.ai.generateImage(imagePromptWithoutText(reply.imagePrompt));
        const key = buildAssetKey({ tenantId: auth.tenantId, kind: 'generated_visual', filename: `visual.${image.mimeType.split('/')[1]}` });
        await this.storage.put({ key, body: image.bytes, contentType: image.mimeType });
        const asset = await this.repo.insertAsset({
          tenantId: auth.tenantId,
          kind: 'generated_visual',
          storageKey: key,
          mimeType: image.mimeType,
          byteSize: image.bytes.length,
          sha256: sha256Hex(image.bytes),
          uploadedBy: auth.userId,
          validationStatus: 'valid',
        });
        return { type: 'image', spec: scene, assetId: asset.id, note: null };
      } catch (error) {
        this.logger.warn(`image generation failed; using the drawn fallback: ${error instanceof Error ? error.message : 'unknown'}`);
      }
    }
    if (scene) return { type: 'illustration', spec: scene, assetId: null, note: 'drawn instead of an image' };
    return { type: 'none', spec: null, assetId: null, note: 'an image would have helped, but image generation is not available on this server' };
  }

  private rejected(): AppException {
    return AppException.unprocessable(
      'A visual for this question could not be made without giving the answer away or breaking the drawing rules, so none is shown. The written explanation is still available.',
      'AI_OUTPUT_REJECTED',
    );
  }

  private async explanationParams(tenantId: string): Promise<ExplanationParams> {
    const active = await this.engineConfig.rawActiveParams(tenantId);
    const parsed = parseExplanationParams(active.params);
    if (!parsed.ok) throw AppException.unprocessable('The active configuration has no usable retrieval settings', 'ENGINE_CONFIG_INVALID');
    return parsed.value;
  }

  private toDto(row: VisualExplanationRow, cached: boolean): VisualExplanationDto {
    const d = row.decision as { concept?: string; reason?: string; title?: string; caption?: string; note?: string };
    return {
      id: row.id,
      questionId: row.questionId,
      visualType: row.visualType,
      title: d.title ?? '',
      caption: d.caption ?? '',
      concept: d.concept ?? '',
      reason: d.note ? `${d.reason ?? ''} (${d.note})`.trim() : (d.reason ?? ''),
      scene: row.spec,
      imageUrl: row.assetId ? `/v1/visuals/${row.id}/image` : null,
      cached,
    };
  }
}

/**
 * The prompt actually sent to an image model.
 *
 * The prompt text is leak-checked, but the pixels that come back are not — an image model can draw an
 * equation or a value nobody asked for. A picture without text cannot spell out an answer, so every image
 * prompt carries this instruction, appended here rather than trusted to the analysis that wrote the prompt.
 * It reduces the risk; it does not check the picture, which is why image generation stays off by default.
 */
export function imagePromptWithoutText(prompt: string): string {
  return `${prompt.trim()}\n\nDraw the picture only. Do not include any text, letters, numbers, labels, equations, arrows pointing at an answer, or highlighted options.`;
}

/** The analysis, kept with the visual: it is what the student is told about why this format. */
function decisionOf(reply: VisualReply): Record<string, unknown> {
  return {
    concept: reply.concept,
    useful: reply.useful,
    reason: reply.reason,
    format: reply.format,
    mustNotShow: reply.mustNotShow,
    title: reply.title,
    caption: reply.caption,
  };
}
